import { Link } from "react-router-dom";
import { Alert, Badge, ErrorState, Skeleton } from "../../../components/ui/Feedback";
import type { CourseDetail, CourseSummary, CourseVersion, GenerationMetadata } from "../schemas/course";

const versionLabel: Record<string, string> = {
  draft: "Draft",
  approved: "Approved",
  superseded: "Superseded",
};

const goalLabel: Record<string, string> = {
  intake: "Intake",
  diagnostic_ready: "Diagnostic ready",
  diagnostic_evaluated: "Diagnostic complete",
  generating: "Generating",
  course_draft: "Draft review",
  approved: "Enrolled",
  failed: "Needs retry",
};

export function VersionBadge({ version }: { version: CourseVersion | null | undefined }) {
  if (!version) return <Badge tone="neutral">No version</Badge>;
  if (version.status === "approved") {
    return <Badge tone="lime">v{version.version_number} approved</Badge>;
  }
  if (version.status === "superseded") {
    return <Badge tone="neutral">v{version.version_number} superseded</Badge>;
  }
  return <Badge tone="warning">v{version.version_number} draft</Badge>;
}

export function GoalStatusBadge({ status }: { status: string }) {
  const tone = status === "approved" ? "lime" : status === "failed" ? "danger" : status === "generating" ? "blue" : "neutral";
  return <Badge tone={tone}>{goalLabel[status] ?? status}</Badge>;
}

export function CourseCard({ course }: { course: CourseSummary }) {
  const hasDraft = course.has_draft && course.draft_version_id;
  return (
    <article className="flex h-full flex-col gap-4 rounded-2xl border border-ink/15 bg-white/50 p-5">
      <div className="flex flex-wrap items-center gap-2">
        <Badge tone={course.status === "approved" ? "lime" : "neutral"}>
          {course.status === "approved" ? "Approved" : course.status}
        </Badge>
        <Badge tone={course.version_status === "draft" ? "warning" : "neutral"}>
          v{course.version_number} {versionLabel[course.version_status] ?? course.version_status}
        </Badge>
        {hasDraft && <Badge tone="blue">New draft</Badge>}
      </div>
      <div>
        <h3 className="text-xl font-semibold tracking-tight">{course.title}</h3>
        <p className="mt-1 line-clamp-3 text-sm text-ink/65">{course.short_description}</p>
      </div>
      <dl className="mt-auto grid grid-cols-3 gap-2 text-center text-xs">
        <div className="rounded-xl bg-ink/5 p-2">
          <dt className="text-ink/55">Modules</dt>
          <dd className="mt-0.5 font-mono text-base">{course.counts.modules}</dd>
        </div>
        <div className="rounded-xl bg-ink/5 p-2">
          <dt className="text-ink/55">Classes</dt>
          <dd className="mt-0.5 font-mono text-base">{course.counts.classes}</dd>
        </div>
        <div className="rounded-xl bg-ink/5 p-2">
          <dt className="text-ink/55">Lessons</dt>
          <dd className="mt-0.5 font-mono text-base">{course.counts.lessons}</dd>
        </div>
      </dl>
      <div className="flex flex-wrap items-center justify-between gap-2">
        <span className="text-xs text-ink/55">
          {Math.round(course.estimated_duration_minutes / 60)}h total · {course.target_learner_level}
        </span>
        {hasDraft ? (
          <Link
            to={`/app/courses/${course.id}/review`}
            className="rounded-full bg-ink px-4 py-2 text-sm font-medium text-paper"
          >
            Review draft
          </Link>
        ) : (
          <Link
            to={`/app/courses/${course.id}`}
            className="rounded-full border border-ink/25 px-4 py-2 text-sm font-medium"
          >
            Open course
          </Link>
        )}
      </div>
    </article>
  );
}

export function CourseStats({ course }: { course: CourseDetail }) {
  const counts = course.counts;
  return (
    <div className="grid grid-cols-2 gap-3 sm:grid-cols-4">
      {[
        ["Modules", counts.modules],
        ["Classes", counts.classes],
        ["Lessons", counts.lessons],
        ["Exercises", counts.exercises],
      ].map(([label, value]) => (
        <div key={label} className="rounded-xl border border-ink/10 bg-white/50 p-3">
          <p className="text-xs text-ink/55">{label}</p>
          <p className="mt-1 font-mono text-2xl">{value}</p>
        </div>
      ))}
    </div>
  );
}

export function ProviderNotice({ metadata }: { metadata: GenerationMetadata }) {
  if (metadata.provider === "mock") {
    return (
      <Alert variant="warning" title="Development provider used">
        This curriculum was generated by the deterministic mock provider, not a live language
        model. It is useful for exercising the flow, but the content is not personalized by an AI
        provider. Mock generation is rejected in production.
      </Alert>
    );
  }
  if (metadata.fallback_used) {
    return (
      <Alert variant="warning" title="Fallback provider used">
        The primary model did not complete this request, so the configured fallback provider was
        used. {metadata.fallback_reason ? `Reason: ${metadata.fallback_reason}` : ""}
      </Alert>
    );
  }
  return (
    <p className="text-xs text-ink/50">
      Generated with {metadata.provider} / {metadata.model} · prompt {metadata.prompt_version || "unknown"}
      {metadata.repaired ? " · output repaired by the validator" : ""}
    </p>
  );
}

export function CourseSkeleton() {
  return (
    <div className="space-y-4" aria-busy="true" aria-label="Loading course">
      <Skeleton className="h-10 w-2/3" />
      <Skeleton className="h-5 w-1/2" />
      <Skeleton className="h-40 w-full" />
      <Skeleton className="h-40 w-full" />
    </div>
  );
}

export function QueryFailure({
  title,
  message,
  onRetry,
}: {
  title: string;
  message: string;
  onRetry?: () => void;
}) {
  return (
    <ErrorState
      title={title}
      hint={message}
      action={
        onRetry ? (
          <button
            type="button"
            onClick={onRetry}
            className="rounded-full border border-ink/25 px-4 py-2 text-sm font-medium"
          >
            Try again
          </button>
        ) : undefined
      }
    />
  );
}

export function CourseTimeline({ course }: { course: CourseDetail }) {
  return (
    <div className="flex flex-wrap items-center gap-2 text-sm">
      <VersionBadge version={course.version} />
      {course.approved_version && course.version?.id !== course.approved_version.id && (
        <>
          <span className="text-ink/40">→</span>
          <VersionBadge version={course.approved_version} />
          <span className="text-xs text-ink/55">remains the enrolled curriculum</span>
        </>
      )}
    </div>
  );
}
