-- ============================================================================
-- FRIKHII Copilot — Phase 04
-- Learning Engine: quiz attempts, exercise submissions, remedial plans,
-- and generated lesson content (extending lesson_contents).
--
-- Apply after the Phase 03.5 migration.
-- Rollback: database/rollbacks/20251105093000_phase_04_learning_engine_down.sql
--
-- Security boundary
-- * Browser roles receive SELECT only on their own rows, always through RLS.
-- * quiz_answer_keys have RLS enabled and NO grants to anon/authenticated.
-- * The Go Core API connects with a privileged role and re-checks ownership.
-- ============================================================================

begin;

-- ---------------------------------------------------------------------------
-- Extend lesson_contents: allow 'authored' content generated by the AI engine
-- ---------------------------------------------------------------------------
alter table public.lesson_contents
  drop constraint if exists lesson_contents_type_check;
alter table public.lesson_contents
  add constraint lesson_contents_type_check
  check (content_type in ('blueprint', 'authored'));

-- ---------------------------------------------------------------------------
-- Add authored_content to exercises for AI-expanded exercise content
-- ---------------------------------------------------------------------------
alter table public.exercises
  add column if not exists authored_content jsonb;

-- ---------------------------------------------------------------------------
-- quiz_attempts
-- ---------------------------------------------------------------------------
create table if not exists public.quiz_attempts (
  id uuid primary key default gen_random_uuid(),
  course_id uuid not null references public.courses (id) on delete cascade,
  course_version_id uuid not null references public.course_versions (id) on delete cascade,
  class_id uuid not null references public.classes (id) on delete cascade,
  user_id uuid not null references public.profiles (id) on delete cascade,
  attempt_number integer not null default 1,
  status text not null default 'generating',
  passing_score integer not null default 70,
  score integer,
  passed boolean,
  summary text,
  strengths jsonb not null default '[]'::jsonb,
  gaps jsonb not null default '[]'::jsonb,
  question_scores jsonb not null default '[]'::jsonb,
  submitted_at timestamptz,
  evaluated_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint quiz_attempts_number_check check (attempt_number > 0),
  constraint quiz_attempts_passing_check check (passing_score between 0 and 100),
  constraint quiz_attempts_score_check check (score is null or score between 0 and 100),
  constraint quiz_attempts_status_check
    check (status in ('generating', 'ready', 'submitted', 'evaluating', 'evaluated', 'failed')),
  constraint quiz_attempts_strengths_check check (jsonb_typeof(strengths) = 'array'),
  constraint quiz_attempts_gaps_check check (jsonb_typeof(gaps) = 'array'),
  constraint quiz_attempts_scores_check check (jsonb_typeof(question_scores) = 'array')
);

comment on table public.quiz_attempts is
  'One quiz run per class per attempt. Answer keys never leave the server.';

create index if not exists quiz_attempts_user_class_idx
  on public.quiz_attempts (user_id, class_id, attempt_number desc);
create index if not exists quiz_attempts_course_idx
  on public.quiz_attempts (course_id, user_id);

drop trigger if exists quiz_attempts_set_updated_at on public.quiz_attempts;
create trigger quiz_attempts_set_updated_at
  before update on public.quiz_attempts
  for each row execute function public.set_updated_at();

-- ---------------------------------------------------------------------------
-- quiz_questions
-- ---------------------------------------------------------------------------
create table if not exists public.quiz_questions (
  id uuid primary key default gen_random_uuid(),
  attempt_id uuid not null references public.quiz_attempts (id) on delete cascade,
  source_id text not null,
  sequence_order integer not null,
  question_type text not null,
  prompt text not null,
  competency text not null,
  difficulty text not null,
  choices jsonb not null default '[]'::jsonb,
  explanation text not null default '',
  created_at timestamptz not null default now(),
  constraint quiz_questions_sequence_check check (sequence_order > 0),
  constraint quiz_questions_type_check
    check (question_type in ('multiple_choice', 'short_answer', 'scenario', 'reasoning')),
  constraint quiz_questions_difficulty_check
    check (difficulty in ('foundation', 'intermediate', 'advanced')),
  constraint quiz_questions_choices_check check (jsonb_typeof(choices) = 'array'),
  constraint quiz_questions_source_check check (char_length(btrim(source_id)) between 1 and 60),
  constraint quiz_questions_attempt_source_key unique (attempt_id, source_id),
  constraint quiz_questions_attempt_sequence_key unique (attempt_id, sequence_order)
);

create index if not exists quiz_questions_attempt_idx
  on public.quiz_questions (attempt_id, sequence_order);

-- ---------------------------------------------------------------------------
-- quiz_answer_keys — private, never granted to browser roles
-- ---------------------------------------------------------------------------
create table if not exists public.quiz_answer_keys (
  question_id uuid primary key references public.quiz_questions (id) on delete cascade,
  expected_answer text not null,
  rubric jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now(),
  constraint quiz_answer_keys_expected_check check (char_length(btrim(expected_answer)) > 0),
  constraint quiz_answer_keys_rubric_check check (jsonb_typeof(rubric) = 'array')
);

comment on table public.quiz_answer_keys is
  'Private grading material for quiz questions. No grants to anon/authenticated.';

-- ---------------------------------------------------------------------------
-- quiz_answers
-- ---------------------------------------------------------------------------
create table if not exists public.quiz_answers (
  id uuid primary key default gen_random_uuid(),
  attempt_id uuid not null references public.quiz_attempts (id) on delete cascade,
  question_id uuid not null references public.quiz_questions (id) on delete cascade,
  user_id uuid not null references public.profiles (id) on delete cascade,
  response text not null,
  score integer,
  feedback text,
  created_at timestamptz not null default now(),
  constraint quiz_answers_response_check check (char_length(response) <= 5000),
  constraint quiz_answers_score_check check (score is null or score between 0 and 100),
  constraint quiz_answers_attempt_question_key unique (attempt_id, question_id)
);

create index if not exists quiz_answers_attempt_idx
  on public.quiz_answers (attempt_id);

-- ---------------------------------------------------------------------------
-- exercise_submissions
-- ---------------------------------------------------------------------------
create table if not exists public.exercise_submissions (
  id uuid primary key default gen_random_uuid(),
  exercise_id uuid not null references public.exercises (id) on delete cascade,
  course_id uuid not null references public.courses (id) on delete cascade,
  user_id uuid not null references public.profiles (id) on delete cascade,
  attempt_number integer not null default 1,
  response text not null,
  score integer,
  feedback text,
  status text not null default 'submitted',
  submitted_at timestamptz not null default now(),
  evaluated_at timestamptz,
  created_at timestamptz not null default now(),
  constraint exercise_submissions_attempt_check check (attempt_number > 0),
  constraint exercise_submissions_score_check check (score is null or score between 0 and 100),
  constraint exercise_submissions_response_check check (char_length(btrim(response)) between 10 and 10000),
  constraint exercise_submissions_status_check
    check (status in ('submitted', 'evaluating', 'evaluated', 'failed'))
);

comment on table public.exercise_submissions is
  'User responses to class exercises. Each row is one submission attempt.';

create index if not exists exercise_submissions_user_exercise_idx
  on public.exercise_submissions (user_id, exercise_id, attempt_number desc);
create index if not exists exercise_submissions_course_idx
  on public.exercise_submissions (course_id, user_id);

-- ---------------------------------------------------------------------------
-- remedial_plans
-- ---------------------------------------------------------------------------
create table if not exists public.remedial_plans (
  id uuid primary key default gen_random_uuid(),
  course_id uuid not null references public.courses (id) on delete cascade,
  class_id uuid not null references public.classes (id) on delete cascade,
  quiz_attempt_id uuid references public.quiz_attempts (id) on delete set null,
  user_id uuid not null references public.profiles (id) on delete cascade,
  status text not null default 'active',
  gap_summary text not null,
  plan jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint remedial_plans_status_check
    check (status in ('active', 'completed', 'superseded')),
  constraint remedial_plans_gap_summary_check
    check (char_length(btrim(gap_summary)) between 10 and 4000),
  constraint remedial_plans_plan_check check (jsonb_typeof(plan) = 'object')
);

comment on table public.remedial_plans is
  'AI-generated remedial study plans for learners who did not pass a class quiz.';

create index if not exists remedial_plans_user_class_idx
  on public.remedial_plans (user_id, class_id, created_at desc);
create index if not exists remedial_plans_course_idx
  on public.remedial_plans (course_id, user_id);

drop trigger if exists remedial_plans_set_updated_at on public.remedial_plans;
create trigger remedial_plans_set_updated_at
  before update on public.remedial_plans
  for each row execute function public.set_updated_at();

-- ---------------------------------------------------------------------------
-- Row Level Security
-- ---------------------------------------------------------------------------
alter table public.quiz_attempts enable row level security;
alter table public.quiz_questions enable row level security;
alter table public.quiz_answer_keys enable row level security;
alter table public.quiz_answers enable row level security;
alter table public.exercise_submissions enable row level security;
alter table public.remedial_plans enable row level security;

-- Revoke all from browser roles first
revoke all on table public.quiz_attempts from anon, authenticated;
revoke all on table public.quiz_questions from anon, authenticated;
revoke all on table public.quiz_answer_keys from anon, authenticated;
revoke all on table public.quiz_answers from anon, authenticated;
revoke all on table public.exercise_submissions from anon, authenticated;
revoke all on table public.remedial_plans from anon, authenticated;

-- Grant read-only SELECT on own rows (quiz_answer_keys deliberately excluded)
grant select on table public.quiz_attempts to authenticated;
grant select on table public.quiz_questions to authenticated;
grant select on table public.quiz_answers to authenticated;
grant select on table public.exercise_submissions to authenticated;
grant select on table public.remedial_plans to authenticated;

-- quiz_attempts: own rows via course ownership
drop policy if exists quiz_attempts_select_own on public.quiz_attempts;
create policy quiz_attempts_select_own on public.quiz_attempts
  for select to authenticated
  using (user_id = (select auth.uid()));

-- quiz_questions: own via quiz_attempt
drop policy if exists quiz_questions_select_own on public.quiz_questions;
create policy quiz_questions_select_own on public.quiz_questions
  for select to authenticated
  using (
    exists (
      select 1 from public.quiz_attempts qa
      where qa.id = attempt_id and qa.user_id = (select auth.uid())
    )
  );

-- quiz_answer_keys: RLS enabled, no policy, no grant. Service role only.

-- quiz_answers: own rows
drop policy if exists quiz_answers_select_own on public.quiz_answers;
create policy quiz_answers_select_own on public.quiz_answers
  for select to authenticated
  using (user_id = (select auth.uid()));

-- exercise_submissions: own rows
drop policy if exists exercise_submissions_select_own on public.exercise_submissions;
create policy exercise_submissions_select_own on public.exercise_submissions
  for select to authenticated
  using (user_id = (select auth.uid()));

-- remedial_plans: own rows
drop policy if exists remedial_plans_select_own on public.remedial_plans;
create policy remedial_plans_select_own on public.remedial_plans
  for select to authenticated
  using (user_id = (select auth.uid()));

commit;
